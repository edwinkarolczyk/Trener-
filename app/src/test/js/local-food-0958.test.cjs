const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const src=fs.readFileSync('app/src/main/assets/v0958-local-food.js','utf8');
const storage=new Map();
const localStorage={getItem:k=>storage.has(k)?storage.get(k):null,
 setItem:(k,v)=>storage.set(k,String(v)),removeItem:k=>storage.delete(k)};
const win={};
vm.runInNewContext(src,{window:win,localStorage,Date,Math},{filename:'local-food-0958.js',timeout:2000});
const api=win.TrenerLocalFood0958;
assert(api,'shared local food API missing');
const BARCODE='5901234123457';
const online={barcode:BARCODE,name:'Twaróg',kcal100:120,protein100:18,carbs100:4,fat100:3,source:'Open Food Facts'};
storage.set('trainer3.openFoodFactsCache.v0802',JSON.stringify({[BARCODE]:{savedAt:1,product:online}}));
assert.equal(api.findBarcode(BARCODE).source,'Open Food Facts','legacy scan cache remains readable');
storage.set('trainer3.openFoodFactsRecent.v0802',JSON.stringify([online]));
assert.equal(api.recents()[0].name,'Twaróg','legacy recents remain readable');
let result=api.saveOwn({...online,name:'Twaróg poprawiony',kcal100:140,protein100:21});
assert.equal(result.ok,true);
assert.equal(api.findBarcode(BARCODE).source,'Własny produkt','user data overrides remote cache');
assert.equal(api.findBarcode(BARCODE).kcal100,140);
assert.equal(api.recents()[0].name,'Twaróg poprawiony');
assert.equal(api.recents().length,1,'legacy recent must deduplicate by barcode');
const firstId=result.product.id;
result=api.saveOwn({...result.product,kcal100:155});
assert.equal(result.ok,true);
assert.equal(api.own().length,1,'editing product must not duplicate it');
assert.equal(result.product.id,firstId);
assert.equal(api.findBarcode(BARCODE).kcal100,155);
result=api.captureMeal({name:'Twaróg poprawiony',barcode:BARCODE,catalogId:firstId,
 grams:200,kcal:400,protein:40,carbs:6,fat:10});
assert.equal(result.ok,true);
assert.equal(api.findBarcode(BARCODE).kcal100,200,'corrected macros saved for 100g');
assert.equal(api.findBarcode(BARCODE).protein100,20);
assert.equal(api.findBarcode(BARCODE).carbs100,3);
assert.equal(api.findBarcode(BARCODE).fat100,5);
assert.equal(api.own().length,1);
result=api.saveOwn({barcode:'12345678',name:'Nieznany z kodem',
 kcal100:77,protein100:1,carbs100:10,fat100:2});
assert.equal(result.ok,true,'manual product with unrecognized barcode should be saved');
assert.equal(api.findBarcode('12345678').name,'Nieznany z kodem');
assert.equal(api.recents()[0].barcode,'12345678');
result=api.captureMeal({name:'Ręczny posiłek',grams:150,kcal:300,protein:15,carbs:30,fat:10});
assert.equal(result.ok,true,'manual single ingredient with known grams enters own catalog');
assert.equal(api.own().length,3);
assert.equal(api.recents()[0].name,'Ręczny posiłek','manual product joins same recent list');
assert.equal(api.captureMeal({name:'Bez gramów',kcal:100,protein:5,carbs:2,fat:1}).skipped,true);
assert.equal(api.own().length,3,'no per-100g assumptions without grams');
assert.equal(api.saveOwn({barcode:'BAD!',name:'Zły kod',kcal100:10}).ok,false);
assert.equal(api.own().length,3);
assert.equal(api.removeOwn(firstId),true);
assert.equal(api.findBarcode(BARCODE).source,'Open Food Facts','after deletion original cache remains available');
assert.equal(api.recents().some(x=>x.id===firstId),false);
const old=api.own();
storage.set('trainer3.foodCatalog.v083',JSON.stringify(Array.from({length:300},(_,i)=>
 ({id:'own:'+i,name:'Pozycja '+i,source:'Własny produkt',kcal100:i}))));
assert.equal(api.saveOwn({name:'301',kcal100:1}).ok,false,'no automatic eviction from own catalog');
assert.equal(api.own().length,300);
assert.equal(api.own()[299].id,'own:299');
assert.equal(api.saveOwn({id:'own:299',name:'Poprawa 299',kcal100:999}).ok,true);
assert.equal(api.own().length,300,'update at limit still allowed');
const backupKeys=[...storage.keys()].filter(x=>x.startsWith('trainer3.'));
assert(backupKeys.includes('trainer3.foodRecent.v0958'),'shared recents included by existing backup contract');
assert(backupKeys.includes('trainer3.foodCatalog.v083'),'existing own products key kept');
const loader=fs.readFileSync('app/src/main/assets/feature-loader.js','utf8');
assert(loader.indexOf('v0958-local-food.js')<loader.indexOf('v0802-openfoodfacts.js'),
 'shared storage loads before scanner');
const scanner=fs.readFileSync('app/src/main/assets/v0802-openfoodfacts.js','utf8');
assert(scanner.includes('TrenerLocalFood0958?.findBarcode(barcode)'));
assert(scanner.includes('v0802NewOwn'));
assert(scanner.includes('OSTATNIO UŻYWANE'));
const catalog=fs.readFileSync('app/src/main/assets/v083-food-catalog.js','utf8');
assert(catalog.includes('v083Barcode'));
assert(catalog.includes('api.saveOwn(p)'));
assert(catalog.includes('openRecent'));
const diet=fs.readFileSync('app/src/main/assets/v076-diet.js','utf8');
const composer=fs.readFileSync('app/src/main/assets/v0885-meal-composer.js','utf8');
assert(diet.includes('TrenerLocalFood0958?.captureMeal'));
assert(composer.includes('TrenerLocalFood0958?.captureMeal'));
assert(diet.includes('if(!save(d))return;'),'save to catalog must follow successful meal save');
console.log('Local food 0.9.5.8: barcode priority, manual entry, corrected macros, recents, cap, backups OK');
